-- ============================================================================
-- AI INTELLIGENCE SUMMARY VIEW
-- ============================================================================


CREATE OR REPLACE VIEW ai.v_intelligence_summary AS

SELECT

'LEAD_INTELLIGENCE' AS intelligence_type,

COUNT(*) AS total_records

FROM ai.lead_intelligence



UNION ALL



SELECT

'CUSTOMER_RISK',

COUNT(*)

FROM ai.customer_risk_scores



UNION ALL



SELECT

'SALES_INSIGHTS',

COUNT(*)

FROM ai.sales_insights;



-- ============================================================================
-- AI RECOMMENDATION PERFORMANCE
-- ============================================================================


CREATE OR REPLACE VIEW ai.v_recommendation_performance AS


SELECT

recommendation_type,

COUNT(*) AS total_generated,

COUNT(*) FILTER
(
    WHERE accepted = TRUE
)
AS accepted_count,


ROUND(

COUNT(*) FILTER
(
    WHERE accepted = TRUE
)::numeric

/

NULLIF(
    COUNT(*),
    0
)

* 100,

2

)

AS acceptance_percentage


FROM ai.recommendations


GROUP BY recommendation_type;



-- ============================================================================
-- AI VALIDATION
-- ============================================================================


CREATE OR REPLACE VIEW ai.v_ai_health AS


SELECT

'ASSISTANTS' AS check_name,

COUNT(*) AS total_records,

'PASS' AS status

FROM ai.assistants



UNION ALL



SELECT

'PROMPTS',

COUNT(*),

'PASS'

FROM ai.prompt_templates



UNION ALL



SELECT

'RECOMMENDATIONS',

COUNT(*),

'PASS'

FROM ai.recommendations;



